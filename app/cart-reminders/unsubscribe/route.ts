import { undoCartReminderUnsubscribe, unsubscribeCartReminder, verifyCartReminderToken } from '@/lib/cart-reminder-server'

const path = '/cart-reminders/unsubscribe'
const preferences = '<p><a href="/privacy/email-preferences">Manage email preferences</a></p>'

function page(title: string, content: string, status = 200) {
  return new Response(`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${title} | YMI Story</title></head><body><main><p>YMI Story</p><h1>${title}</h1>${content}</main></body></html>`, {
    status,
    headers: {
      'Content-Type': 'text/html; charset=utf-8',
      'Cache-Control': 'no-store',
      'Referrer-Policy': 'no-referrer',
    },
  })
}

const invalid = () => page('Invalid unsubscribe link', '<p>Please open the link from your cart reminder email.</p>' + preferences, 400)

function form(action: 'unsubscribe' | 'undo', token: string, label: string) {
  // Tokens are checked by the verifier or generated by the server before rendering.
  return `<form method="post" action="${path}"><input type="hidden" name="action" value="${action}"><input type="hidden" name="token" value="${token}"><button type="submit">${label}</button></form>`
}

export function GET(request: Request) {
  const token = new URL(request.url).searchParams.get('token')
  if (!token || !verifyCartReminderToken(token, 'unsubscribe')) return invalid()
  return page('Unsubscribe from cart reminders', '<p>This stops weekly cart reminders.</p>' + form('unsubscribe', token, 'Confirm unsubscribe'))
}

async function readForm(request: Request) {
  const contentType = request.headers.get('content-type')
  const type = contentType?.split(';', 1)[0].trim().toLowerCase()
  if (type !== 'application/x-www-form-urlencoded' && type !== 'multipart/form-data') return null
  const reader = request.body?.getReader()
  if (!reader || !contentType) return null
  const chunks: Uint8Array[] = []
  let size = 0
  try {
    for (;;) {
      const { value, done } = await reader.read()
      if (done) break
      size += value.byteLength
      if (size > 1024) {
        await reader.cancel()
        return null
      }
      chunks.push(value)
    }
    return await new Response(Buffer.concat(chunks), { headers: { 'Content-Type': contentType } }).formData()
  } catch {
    return null
  } finally {
    reader.releaseLock()
  }
}

export async function POST(request: Request) {
  const fields = await readForm(request)
  if (!fields) return invalid()
  const native = fields.get('List-Unsubscribe') === 'One-Click' && [...fields].length === 1
  const action = native ? 'unsubscribe' : fields.get('action')
  if (action !== 'unsubscribe' && action !== 'undo') return invalid()
  if (!native && [...fields].length !== 2) return invalid()
  // A signed capability is the sole authority. No-Referrer form navigations may send Origin: null.
  const token = native ? new URL(request.url).searchParams.get('token') : fields.get('token')
  const id = verifyCartReminderToken(typeof token === 'string' ? token : null, action)
  if (!id) return invalid()
  try {
    if (action === 'undo') {
      if (!(await undoCartReminderUnsubscribe(id))) {
        return page('This undo link is no longer valid', '<p>You can turn reminders back on in Email Preferences.</p>' + preferences, 410)
      }
      return page('Cart reminders restored', '<p>You can turn them off again in Email Preferences.</p>' + preferences)
    }
    const result = await unsubscribeCartReminder(id, !native)
    if (native) return new Response(null, { status: 204, headers: { 'Cache-Control': 'no-store' } })
    if (!result) return invalid()
    return page('You’re unsubscribed', '<p>You won’t receive weekly cart reminders anymore.</p>'
      + (result.undoToken ? form('undo', result.undoToken, 'Restore cart reminders') : preferences))
  } catch {
    return page('Could not save your change', '<p>Please try again.</p>' + preferences, 503)
  }
}
